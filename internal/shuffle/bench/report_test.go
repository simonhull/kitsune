// table is a markdown table being built.
type table struct {
	b *strings.Builder
}

// newTable starts a table with a heading and columns.
func newTable(b *strings.Builder, heading string, columns ...string) table {
	fmt.Fprintf(b, "\n## %s\n\n| %s |\n|%s\n", heading, strings.Join(columns, " | "), strings.Repeat(" --- |", len(columns)))
	return table{b: b}
}

// row adds a row.
func (t table) row(cells ...string) {
	fmt.Fprintf(t.b, "| %s |\n", strings.Join(cells, " | "))
}

// note adds a line under the table.
func (t table) note(text string) { fmt.Fprintf(t.b, "\n%s\n", text) }

// per1000 is n of total, per thousand.
func per1000(n, total int) string { return fmt.Sprintf("%.2f", 1000*float64(n)/float64(max(1, total))) }

// pct is n of total, as a percentage.
func pct(n, total int) string {
	if total == 0 {
		return "–"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(n)/float64(total))
}

// num formats a float to three places.
func num(x float64) string { return fmt.Sprintf("%.3f", x) }

func TestReport(t *testing.T) {
	t.Parallel()
	libs := make([]library, 0, len(shapes()))
	for _, sh := range shapes() {
		libs = append(libs, generate(sh))
	}
	var b strings.Builder
	b.WriteString("# Shuffle bench\n\nGenerated by `go test -run Report -v ./internal/shuffle/bench`" +
		" (`UPDATE_BASELINE=1` rewrites this file). Every figure is the shuffle's, next to a naive" +
		" Fisher–Yates shuffle of the songs that knows nothing of runs, skips, weights or spacing.\n")
	libraries(&b, libs)
	finite(t, &b, libs)
	endless(t, &b, libs)
	weights(t, &b, &libs[0])
	flow(t, &b, &libs[0])
	signals(t, &b)
	explain(t, &b, &libs[0])
	t.Log("\n" + b.String())
	if os.Getenv("UPDATE_BASELINE") != "" {
		if err := os.WriteFile("BASELINE.md", []byte(b.String()), 0o644); err != nil { //nolint:gosec // G306: a report in the repository, meant to be read.
			t.Fatalf("writing BASELINE.md: %v", err)
		}
	}
}

// libraries describes the generated libraries.
func libraries(b *strings.Builder, libs []library) {
	tb := newTable(b, "Libraries", "library", "songs", "artists", "albums", "runs", "skipped", "top artist")
	for i := range libs {
		l := &libs[i]
		artists, albums := map[shuffle.ArtistID]int{}, map[shuffle.AlbumID]bool{}
		skipped := 0
		for j := range l.tracks {
			artists[l.tracks[j].Artists[0]]++
			albums[l.tracks[j].Album] = true
			if l.tracks[j].Skipped {
				skipped++
			}
		}
		top := 0
		for _, n := range artists {
			top = max(top, n)
		}
		tb.row(l.name, strconv.Itoa(len(l.tracks)), strconv.Itoa(len(artists)), strconv.Itoa(len(albums)),
			strconv.Itoa(len(l.runs)), strconv.Itoa(skipped), pct(top, len(l.tracks)))
	}
}

// pool builds lib's pool.
func pool(tb testing.TB, lib *library) *shuffle.Pool {
	tb.Helper()
	p, err := shuffle.NewPool(lib.tracks, lib.runs)
	if err != nil {
		tb.Fatalf("%s: NewPool: %v", lib.name, err)
	}
	return p
}

// roomy reports whether lib's set leaves room for the full spacing rules: no
// artist with a quarter of its songs and no album with an eighth. Spacing
// breaks are a failure only then; a smaller set scales its rules down.
func roomy(lib *library) bool {
	artists, albums := map[shuffle.ArtistID]int{}, map[shuffle.AlbumID]int{}
	for i := range lib.tracks {
		artists[lib.tracks[i].Artists[0]]++
		albums[lib.tracks[i].Album]++
	}
	n := len(lib.tracks)
	for _, k := range artists {
		if k*shuffle.ArtistGap >= n {
			return false
		}
	}
	for _, k := range albums {
		if k*shuffle.AlbumGap >= n {
			return false
		}
	}
	return true
}

// finiteSeeds is how many finite orders the bench makes of a library.
func finiteSeeds(lib *library) uint64 {
	switch {
	case len(lib.tracks) >= 10_000:
		return 4
	case len(lib.tracks) <= 100:
		return 500
	}
	return 60
}

// order tallies finite orders.
type order struct {
	units, artistNear, albumNear, longest int
	spread                                float64
	intact, broken, banned                int
	place                                 [shuffle.MaxStars + 1]float64
	placed                                [shuffle.MaxStars + 1]int
}

// add tallies one order.
func (o *order) add(seq []item, e *expected) {
	a := near(seq)
	o.units += len(seq)
	o.artistNear += a.artists
	o.albumNear += a.albums
	o.longest = max(o.longest, streak(seq))
	o.spread += gapSpread(seq)
	r := e.rules(seq)
	o.intact += r.intact
	o.broken += r.broken
	o.banned += r.banned
	positions(seq, &o.place, &o.placed)
}

// finite reports finite orders of every library.
func finite(t *testing.T, b *strings.Builder, libs []library) {
	t.Helper()
	tb := newTable(b, "Finite: every unit once", "library", "metric", "shuffle", "naive")
	for i := range libs {
		lib := &libs[i]
		p := pool(t, lib)
		e := expect(lib)
		ids := make([]shuffle.TrackID, len(lib.tracks))
		for j := range ids {
			ids[j] = lib.tracks[j].ID
		}
		var ours, naive order
		seeds := finiteSeeds(lib)
		c := shuffle.Config{Settings: shuffle.DefaultSettings(), Now: now}
		for seed := range seeds {
			ours.add(fromPicks(shuffle.Finite(p, c, seed, 0)), &e)
			r := rng(seed, 1)
			r.Shuffle(len(ids), func(a, b int) { ids[a], ids[b] = ids[b], ids[a] })
			naive.add(fromTracks(lib, ids), &e)
		}
		rows := [][3]string{
			{"artist within 4, per 1000", per1000(ours.artistNear, ours.units), per1000(naive.artistNear, naive.units)},
			{"album within 8, per 1000", per1000(ours.albumNear, ours.units), per1000(naive.albumNear, naive.units)},
			{"longest artist streak", strconv.Itoa(ours.longest), strconv.Itoa(naive.longest)},
			{"gap spread (CV, 0 is even)", num(ours.spread / float64(seeds)), num(naive.spread / float64(seeds))},
			{"runs intact", pct(ours.intact, ours.intact+ours.broken), pct(naive.intact, naive.intact+naive.broken)},
			{"skipped songs played, per 1000", per1000(ours.banned, ours.units), per1000(naive.banned, naive.units)},
			{"mean place of 5★ / 1★ (0 first)", places(&ours), places(&naive)},
		}
		for _, r := range rows {
			tb.row(lib.name, r[0], r[1], r[2])
		}
		hardRules(t, lib, "finite", ours.broken, ours.banned)
		if roomy(lib) && ours.artistNear+ours.albumNear > 0 {
			t.Errorf("%s finite: %d artist and %d album spacing breaks in a set with room", lib.name, ours.artistNear, ours.albumNear)
		}
	}
	tb.note(fmt.Sprintf("Orders per library: %d (50k: 4, tiny album: 500), at the default settings.", 60))
}

// places is the mean place of 5★ and 1★ items.
func places(o *order) string {
	at := func(c int) float64 { return o.place[c] / float64(max(1, o.placed[c])) }
	return fmt.Sprintf("%.2f / %.2f", at(5), at(1))
}

// hardRules fails the test for any broken run or skipped song played.
func hardRules(t *testing.T, lib *library, mode string, broken, banned int) {
	t.Helper()
	if broken > 0 {
		t.Errorf("%s %s: %d run songs played out of their run", lib.name, mode, broken)
	}
	if banned > 0 {
		t.Errorf("%s %s: %d skipped songs played", lib.name, mode, banned)
	}
}

// endlessPicks is how many picks an endless run of lib takes: two passes
// over a small library, a few days of a large one.
func endlessPicks(lib *library) int {
	if len(lib.tracks) >= 10_000 {
		return 2000
	}
	return 2 * len(lib.tracks)
}

// endless reports endless shuffles of every library but the tiny album.
func endless(t *testing.T, b *strings.Builder, libs []library) {
	t.Helper()
	tb := newTable(b, "Endless: a page a day", "library", "metric", "shuffle", "naive")
	for i := range libs {
		lib := &libs[i]
		if len(lib.tracks) < 100 {
			continue
		}
		e := expect(lib)
		picks := endlessPicks(lib)
		s := newSession(t, lib, shuffle.DefaultSettings(), nil, neutral{}, 11)
		ours := fromPicks(s.play(picks))
		naive := fromTracks(lib, naivePasses(lib, picks, 11))
		size := s.pool.Len()
		on, nn := near(ours), near(naive)
		oc, nc := coverage(ours, size), coverage(naive, len(lib.tracks))
		or, nr := e.rules(ours), e.rules(naive)
		rows := [][3]string{
			{"artist within 4, per 1000", per1000(on.artists, picks), per1000(nn.artists, picks)},
			{"album within 8, per 1000", per1000(on.albums, picks), per1000(nn.albums, picks)},
			{"longest artist streak", strconv.Itoa(streak(ours)), strconv.Itoa(streak(naive))},
			{"gap spread (CV, 0 is even)", num(gapSpread(ours)), num(gapSpread(naive))},
			{"units played in the first pool-size picks", pct(int(oc.share*1000), 1000), pct(int(nc.share*1000), 1000)},
			{"longest wait, in pool sizes", num(float64(oc.wait) / float64(size)), num(float64(nc.wait) / float64(len(lib.tracks)))},
			{"units never played", strconv.Itoa(oc.never), strconv.Itoa(nc.never)},
			{"runs intact", pct(or.intact, or.intact+or.broken), pct(nr.intact, nr.intact+nr.broken)},
			{"skipped songs played, per 1000", per1000(or.banned, picks), per1000(nr.banned, picks)},
		}
		for _, r := range rows {
			tb.row(lib.name, r[0], r[1], r[2])
		}
		hardRules(t, lib, "endless", or.broken, or.banned)
		if roomy(lib) && on.artists+on.albums > 0 {
			t.Errorf("%s endless: %d artist and %d album spacing breaks in a set with room", lib.name, on.artists, on.albums)
		}
	}
	tb.note("Two passes' worth of picks over each library (50k: 2,000), 50 a day, the listener hearing every song" +
		" through, so recency counts. The naive shuffle plays the songs through in one random order, then another.")
}

// naivePasses is picks songs of lib: shuffled, played through, shuffled
// again.
func naivePasses(lib *library, picks int, seed uint64) []shuffle.TrackID {
	r := rng(seed, 2)
	ids := make([]shuffle.TrackID, len(lib.tracks))
	for j := range ids {
		ids[j] = lib.tracks[j].ID
	}
	out := make([]shuffle.TrackID, 0, picks)
	for len(out) < picks {
		r.Shuffle(len(ids), func(a, b int) { ids[a], ids[b] = ids[b], ids[a] })
		out = append(out, ids[:min(len(ids), picks-len(out))]...)
	}
	return out
}

// weights reports how closely endless plays follow the weights, at three
// settings of how much ratings matter.
func weights(t *testing.T, b *strings.Builder, lib *library) {
	t.Helper()
	tb := newTable(b, "Fidelity: plays against weights ("+lib.name+")",
		"ratings matter", "distance (0 is exact)", "naive distance", "5★ : 1★ plays", "5★ : 1★ weight")
	picks := 2 * len(lib.tracks)
	for _, s := range []float64{0, 0.5, 1} {
		settings := shuffle.Settings{Ratings: s, Memory: true}
		var weight [shuffle.MaxStars + 1]float64
		var count [shuffle.MaxStars + 1]int
		units := pool(t, lib).Units()
		for j := range units {
			r := shuffle.Explain(&units[j], settings, now)
			c := int(math.Round(r.Stars))
			weight[c] += r.Rating * r.Heart
			count[c]++
		}
		ours := fromPicks(newSession(t, lib, settings, nil, neutral{}, 12).play(picks))
		got := fidelity(ours, &weight, &count)
		naive := fidelity(fromTracks(lib, naivePasses(lib, picks, 12)), &weight, &count)
		tb.row(num(s), num(got.tv), num(naive.tv), num(got.plays), num(got.weights))
		if s > 0 && got.plays <= 1 {
			t.Errorf("ratings %v: 5★ units played no more than 1★ units (%.2f)", s, got.plays)
		}
	}
	tb.note("Distance is the total variation between plays by rating and weight by rating, the weight" +
		" being rating × heart. The no-repeat window and recency hold plays closer to even than the" +
		" weights alone would, by design, and spacing caps an artist at one unit in four, which holds" +
		" back this library's biggest artist and the ratings it tends to get, even with ratings off.")
}
